export type CityIconSlug = keyof typeof CITY_GLYPHS;

export function hasCityIcon(slug: string): slug is CityIconSlug {
  return slug in CITY_GLYPHS;
}

/**
 * Renders the landmark for a city, falling back to a generic building so a city
 * without artwork still gets a correctly sized glyph rather than an empty box.
 */
export function CityIcon({ slug, className }: { slug: string; className?: string }) {
  if (!hasCityIcon(slug)) {
    return <Building2 className={cn('size-6', className)} aria-hidden="true" />;
  }

  const glyph = CITY_GLYPHS[slug];

  return (
    <svg
      viewBox={glyph.viewBox}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={cn('size-6', className)}
    >
      {glyph.paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}
